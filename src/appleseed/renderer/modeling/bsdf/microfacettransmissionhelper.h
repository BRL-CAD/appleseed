#pragma once

#include "renderer/global/globaltypes.h"
#include "foundation/math/fresnel.h"
#include "foundation/math/microfacet.h"
#include "foundation/math/scalar.h"
#include "foundation/math/vector.h"

#include <algorithm>
#include <cmath>

namespace renderer
{

// Shared transmission geometry, value and directional density from Walter
// et al., Microfacet Models for Refraction through Rough Surfaces (2007).
// [1] https://www.graphics.cornell.edu/~bjw/microfacetbsdf.pdf
// eta is the transmitted/incident index ratio; wo and wi point away from
// the interface. Adjoint transport uses importance rather than radiance.
template <typename MDF>
class MicrofacetTransmissionHelper
{
  public:
    static float fresnel(const float cosine, const float eta, float& transmitted_cosine)
    {
        const float ratio = 1.0f / eta;
        const float transmitted_cosine_squared = foundation::fresnel_transmitted_cosine_squared(ratio, cosine);
        if (transmitted_cosine_squared < 0.0f)
        {
            transmitted_cosine = 0.0f;
            return 1.0f;
        }
        transmitted_cosine = std::min(std::sqrt(std::max(0.0f, transmitted_cosine_squared)), 1.0f);
        float result;
        foundation::fresnel_reflectance_dielectric(result, ratio, std::abs(cosine), transmitted_cosine);
        return result;
    }

    static float fresnel(const float cosine, const float eta)
    {
        float transmitted_cosine;
        return fresnel(cosine, eta, transmitted_cosine);
    }

    static foundation::Vector3f half_vector(
        const foundation::Vector3f&   wo,
        const foundation::Vector3f&   wi,
        const float                   eta)
    {
        // [1] eq. 16.
        const foundation::Vector3f h = normalize(wo + eta * wi);
        return h.y < 0.0f ? -h : h;
    }

    static bool valid_facet(
        const foundation::Vector3f&   wo,
        const foundation::Vector3f&   wi,
        const foundation::Vector3f&   m)
    {
        // Refraction must cross the facet as well as the macrosurface.
        // Other half vectors cannot be generated by the Snell sampler.
        return dot(wo, m) * wo.y > 0.0f && dot(wi, m) * wi.y > 0.0f;
    }

    static void evaluate(
        const float                   eta,
        const Spectrum&               refraction_color,
        const bool                    adjoint,
        const foundation::Vector3f&   wo,
        const foundation::Vector3f&   wi,
        const foundation::Vector3f&   m,
        const float                   alpha_x,
        const float                   alpha_y,
        const float                   T,
        Spectrum&                     value)
    {
        if (wo.y == 0.0f || wi.y == 0.0f)
        {
            value.set(0.0f);
            return;
        }

        // [1] eq. 21.
        const float cos_ih = dot(m, wi);
        const float cos_oh = dot(m, wo);
        const float dots = (cos_ih * cos_oh) / (wi.y * wo.y);

        // Near-matching media have a narrow but finite lobe. Only exact
        // cancellation is singular; a fixed cutoff removes valid transport.
        const float sqrt_denom = cos_oh + eta * cos_ih;
        if (sqrt_denom == 0.0f)
        {
            value.set(0.0f);
            return;
        }

        const float D = MDF::D(m, alpha_x, alpha_y);
        const float G = MDF::G(wi, wo, m, alpha_x, alpha_y);

        float multiplier = std::abs(dots) * T * D * G / foundation::square(sqrt_denom);

        // The transmission PDF contains eta squared. Radiance retains
        // its reciprocal correction; importance transport cancels it.
        if (adjoint)
            multiplier *= foundation::square(eta);

        value = refraction_color;
        value *= multiplier;
    }

    static float pdf(
        const foundation::Vector3f&   wo,
        const foundation::Vector3f&   wi,
        const foundation::Vector3f&   m,
        const float                   alpha_x,
        const float                   alpha_y,
        const float                   eta)
    {
        // [1] eq. 17.
        const float cos_ih = dot(m, wi);
        const float cos_oh = dot(m, wo);

        const float sqrt_denom = cos_oh + eta * cos_ih;
        if (sqrt_denom == 0.0f)
            return 0.0f;

        const float jacobian = std::abs(cos_ih) * foundation::square(eta / sqrt_denom);
        return jacobian * MDF::pdf(wo, m, alpha_x, alpha_y);
    }
};

} // namespace renderer
